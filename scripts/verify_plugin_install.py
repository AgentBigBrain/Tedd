#!/usr/bin/env python3
"""Compare a quiescent installed plugin with an independently reviewed source tree.

This is a read-only byte comparison, not an installer or an authenticity verdict.
The caller must select the trusted source commit and stop concurrent updates.
No files, including generated bytecode, are silently excluded.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import stat
from pathlib import Path


def _reject_link(path: Path) -> os.stat_result:
    metadata = path.lstat()
    if getattr(metadata, "st_file_attributes", 0) & 0x400 or stat.S_ISLNK(metadata.st_mode):
        raise ValueError("Package comparison refuses links and reparse points")
    return metadata


def _plain_root(path: Path) -> Path:
    lexical = Path(os.path.abspath(path.expanduser()))
    for component in (*reversed(lexical.parents), lexical):
        _reject_link(component)
    if not lexical.is_dir():
        raise ValueError("Package comparison requires directory roots")
    return lexical.resolve(strict=True)


def _raise_walk_error(error: OSError) -> None:
    raise error


def _manifest(root: Path) -> dict[str, str]:
    manifest: dict[str, str] = {}
    for directory, directories, files in os.walk(
        root, onerror=_raise_walk_error, followlinks=False
    ):
        parent = Path(directory)
        for name in directories:
            _reject_link(parent / name)
        for name in files:
            path = parent / name
            before = _reject_link(path)
            if not stat.S_ISREG(before.st_mode):
                raise ValueError("Package comparison requires regular files")
            digest = hashlib.sha256()
            with path.open("rb") as handle:
                opened = os.fstat(handle.fileno())
                if (before.st_dev, before.st_ino) != (opened.st_dev, opened.st_ino):
                    raise ValueError("Package file changed before reading")
                for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                    digest.update(chunk)
                after = os.fstat(handle.fileno())
            if (opened.st_size, opened.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
                raise ValueError("Package file changed while reading")
            manifest[path.relative_to(root).as_posix()] = digest.hexdigest()
    return manifest


def _manifest_digest(manifest: dict[str, str]) -> str:
    payload = json.dumps(manifest, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def compare_installation(source: Path, installed: Path) -> dict[str, object]:
    """Report all byte differences; require independent, non-overlapping roots."""

    source = _plain_root(source)
    installed = _plain_root(installed)
    if source.is_relative_to(installed) or installed.is_relative_to(source):
        raise ValueError("Source and installation must be independent trees")
    expected = _manifest(source)
    actual = _manifest(installed)
    if not expected:
        raise ValueError("An empty source cannot qualify an installation")
    missing = sorted(expected.keys() - actual.keys())
    unexpected = sorted(actual.keys() - expected.keys())
    changed = sorted(
        name for name in expected.keys() & actual.keys() if expected[name] != actual[name]
    )
    return {
        "ok": not (missing or unexpected or changed),
        "source_files": len(expected),
        "installed_files": len(actual),
        "source_manifest_sha256": _manifest_digest(expected),
        "installed_manifest_sha256": _manifest_digest(actual),
        "missing": missing,
        "unexpected": unexpected,
        "changed": changed,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source", type=Path, required=True, help="reviewed clean plugin directory"
    )
    parser.add_argument(
        "--installed", type=Path, required=True, help="actual installed plugin directory"
    )
    args = parser.parse_args()
    try:
        result = compare_installation(args.source, args.installed)
    except (OSError, ValueError):
        print(json.dumps({"ok": False, "error": "installation_comparison_unavailable"}))
        return 2
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0 if result["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
